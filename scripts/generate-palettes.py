#!/usr/bin/env python3
"""Regenerate src/ModusThemes/ModusPalette.class.st from the upstream Emacs sources.

Usage:
    git clone https://github.com/protesilaos/modus-themes /tmp/modus-themes
    python3 scripts/generate-palettes.py /tmp/modus-themes/modus-themes.el

Every named color and every semantic mapping of the eight Modus palettes is
written out, with mappings already resolved to their hexadecimal value, so the
Pharo side can look up `#'bg-main'`, `#string`, `#'fg-heading-1'` and so on
exactly as they are named in the Emacs manual.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import modus_palettes  # noqa: E402

TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ModusThemes", "ModusPalette.class.st")


def selector(variant):
    head, *rest = variant.split("-")
    return head + "".join(p.capitalize() for p in rest) + "Entries"


HEADER = '''"
I am one of the eight Modus palettes, ported verbatim from the Emacs modus-themes by Protesilaos Stavrou (https://protesilaos.com/emacs/modus-themes).

I map the color names used upstream (`#'bg-main'`, `#'fg-dim'`, `#'blue-warmer'`, ...) and the semantic mappings (`#string`, `#keyword`, `#comment`, `#'bg-completion'`, ...) to instances of `Color`. Mappings are resolved at generation time, so every key answers a concrete color.

Get a palette with:

```
ModusPalette vivendi.
ModusPalette named: #operandiTinted.
ModusPalette vivendi at: #'bg-main'.
ModusPalette variantNames.
```

The class side `*Entries` methods are GENERATED by `scripts/generate-palettes.py` from upstream `modus-themes.el`. Do not edit them by hand.
"
Class {
	#name : #ModusPalette,
	#superclass : #Object,
	#instVars : [
		'name',
		'colors',
		'hexes'
	],
	#classInstVars : [
		'cache'
	],
	#category : #'ModusThemes-Palette'
}

{ #category : #accessing }
ModusPalette class >> darkVariantNames [

	^ #( #vivendi #vivendiTinted #vivendiDeuteranopia #vivendiTritanopia )
]

{ #category : #accessing }
ModusPalette class >> lightVariantNames [

	^ #( #operandi #operandiTinted #operandiDeuteranopia #operandiTritanopia )
]

{ #category : #accessing }
ModusPalette class >> named: aSymbol [
	"Answer the (cached) palette for the variant named aSymbol, e.g. #vivendiTinted."

	(self variantNames includes: aSymbol asSymbol) ifFalse: [
		^ self error: 'Unknown Modus variant: ' , aSymbol printString ].
	cache ifNil: [ cache := IdentityDictionary new ].
	^ cache at: aSymbol asSymbol ifAbsentPut: [
		  self new
			  setName: aSymbol asSymbol
			  entries: (self perform: (aSymbol , 'Entries') asSymbol) ]
]

{ #category : #'instance creation' }
ModusPalette class >> operandi [

	^ self named: #operandi
]

{ #category : #'instance creation' }
ModusPalette class >> operandiDeuteranopia [

	^ self named: #operandiDeuteranopia
]

{ #category : #'instance creation' }
ModusPalette class >> operandiTinted [

	^ self named: #operandiTinted
]

{ #category : #'instance creation' }
ModusPalette class >> operandiTritanopia [

	^ self named: #operandiTritanopia
]

{ #category : #accessing }
ModusPalette class >> resetCache [
	<script>

	cache := nil
]

{ #category : #accessing }
ModusPalette class >> variantNames [

	^ self lightVariantNames , self darkVariantNames
]

{ #category : #'instance creation' }
ModusPalette class >> vivendi [

	^ self named: #vivendi
]

{ #category : #'instance creation' }
ModusPalette class >> vivendiDeuteranopia [

	^ self named: #vivendiDeuteranopia
]

{ #category : #'instance creation' }
ModusPalette class >> vivendiTinted [

	^ self named: #vivendiTinted
]

{ #category : #'instance creation' }
ModusPalette class >> vivendiTritanopia [

	^ self named: #vivendiTritanopia
]

{ #category : #accessing }
ModusPalette >> at: aSymbol [
	"Answer the Color named aSymbol, e.g. #'bg-main' or #string."

	^ colors at: aSymbol asSymbol ifAbsent: [
		  self error: 'Modus ' , name , ' has no color named ' , aSymbol printString ]
]

{ #category : #accessing }
ModusPalette >> at: aSymbol ifAbsent: aBlock [

	^ colors at: aSymbol asSymbol ifAbsent: aBlock
]

{ #category : #accessing }
ModusPalette >> colorNames [

	^ colors keys asSortedCollection asArray
]

{ #category : #contrast }
ModusPalette >> contrastBetween: aSymbol and: anotherSymbol [
	"Answer the WCAG contrast ratio between two colors of the receiver."

	^ self class contrastRatioOf: (self at: aSymbol) and: (self at: anotherSymbol)
]

{ #category : #accessing }
ModusPalette >> hexAt: aSymbol [
	"Answer the upstream hexadecimal value of aSymbol, e.g. '000000'."

	^ hexes at: aSymbol asSymbol
]

{ #category : #accessing }
ModusPalette >> includesKey: aSymbol [

	^ colors includesKey: aSymbol asSymbol
]

{ #category : #testing }
ModusPalette >> isDark [

	^ self class darkVariantNames includes: name
]

{ #category : #testing }
ModusPalette >> isLight [

	^ self isDark not
]

{ #category : #accessing }
ModusPalette >> name [

	^ name
]

{ #category : #printing }
ModusPalette >> printOn: aStream [

	aStream
		nextPutAll: 'Modus ';
		nextPutAll: name
]

{ #category : #initialization }
ModusPalette >> setName: aSymbol entries: anArray [

	name := aSymbol.
	colors := IdentityDictionary new.
	hexes := IdentityDictionary new.
	anArray pairsDo: [ :key :hex |
		hexes at: key put: hex.
		colors at: key put: (Color fromHexString: hex) ]
]

{ #category : #contrast }
ModusPalette class >> contrastRatioOf: aColor and: anotherColor [
	"Answer the WCAG 2 contrast ratio between two colors (1 to 21)."

	| l1 l2 |
	l1 := self relativeLuminanceOf: aColor.
	l2 := self relativeLuminanceOf: anotherColor.
	^ ((l1 max: l2) + 0.05) / ((l1 min: l2) + 0.05)
]

{ #category : #contrast }
ModusPalette class >> relativeLuminanceOf: aColor [
	"WCAG 2 relative luminance."

	| channel |
	channel := [ :c |
	           c <= 0.03928
		           ifTrue: [ c / 12.92 ]
		           ifFalse: [ (c + 0.055) / 1.055 raisedTo: 2.4 ] ].
	^ (0.2126 * (channel value: aColor red))
	  + (0.7152 * (channel value: aColor green))
	  + (0.0722 * (channel value: aColor blue))
]
'''


def entries_method(variant, entries):
    lines = ["", "{ #category : #'generated palettes' }",
             "ModusPalette class >> %s [" % selector(variant),
             '\t"GENERATED from modus-themes-%s-palette. Do not edit."' % variant,
             "", "\t^ #("]
    for name, value in entries:
        lines.append("\t\t#'%s' '%s'" % (name, value))
    lines.append("\t)")
    lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    palettes = modus_palettes.load(sys.argv[1])
    with open(TARGET, "w", encoding="utf-8", newline="\n") as out:
        out.write(HEADER)
        for variant in modus_palettes.VARIANTS:
            out.write(entries_method(variant, palettes[variant]))
    print("wrote", os.path.normpath(TARGET))


if __name__ == "__main__":
    main()
