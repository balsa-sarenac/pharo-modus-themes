#!/usr/bin/env python3
"""Regenerate src/ModusThemes/ModusPaletteData.class.st from upstream.

    git clone https://github.com/protesilaos/modus-themes /tmp/modus-themes
    python3 scripts/generate-palettes.py /tmp/modus-themes/modus-themes.el
"""
import os
import re
import sys

VARIANTS = [
    "operandi", "operandi-tinted", "operandi-deuteranopia", "operandi-tritanopia",
    "vivendi", "vivendi-tinted", "vivendi-deuteranopia", "vivendi-tritanopia",
]
ENTRY = re.compile(r'^\s*\(([a-z0-9-]+)\s+("#[0-9a-fA-F]{6}"|[a-z0-9-]+)\)', re.M)
TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "src", "ModusThemes", "ModusPaletteData.class.st")


def entries(source, const, end_marker):
    start = source.index("(defconst " + const)
    return [(n, v.strip('"')) for n, v in ENTRY.findall(source[start:source.index(end_marker, start + 1)])]


def palette(source, common, variant):
    own = entries(source, "modus-themes-%s-palette" % variant, '"The entire palette')
    raw = dict(common)
    raw.update(own)
    names = [n for n, _ in own] + [n for n, _ in common if n not in dict(own)]

    def resolve(name):
        value = raw[name]
        if value.startswith("#"):
            return value[1:].lower()
        return None if value == "unspecified" else resolve(value)

    return [(n, resolve(n)) for n in names if resolve(n)]


def selector(variant):
    head, *rest = variant.split("-")
    return head + "".join(p.capitalize() for p in rest)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = open(sys.argv[1], encoding="utf-8").read()
    common = entries(source, "modus-themes-common-palette-mappings", "(defconst")
    out = ['"\nGenerated by scripts/generate-palettes.py from upstream modus-themes.el. Do not edit.\n"',
           "Class {", "\t#name : #ModusPaletteData,", "\t#superclass : #Object,",
           "\t#category : #'ModusThemes-Palette'", "}"]
    for variant in VARIANTS:
        out += ["", "{ #category : #palettes }", "ModusPaletteData class >> %s [" % selector(variant), "", "\t^ #("]
        out += ["\t\t#'%s' '%s'" % pair for pair in palette(source, common, variant)]
        out += ["\t)", "]"]
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
